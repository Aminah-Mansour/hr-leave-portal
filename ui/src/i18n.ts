function getInitialLanguage(): 'en' | 'ar' {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}

function applyDocumentLanguage(language: string) {
  if (typeof document === 'undefined') return
  const normalized = language.startsWith('ar') ? 'ar' : 'en'
  document.documentElement.lang = normalized
  document.documentElement.dir = normalized === 'ar' ? 'rtl' : 'ltr'
}

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: english },
    ar: { translation: arabic },
  },
  lng: getInitialLanguage(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'ar'],
  interpolation: { escapeValue: false },
  react: { useSuspense: false },
})

i18n.on('languageChanged', (language) => {
  applyDocumentLanguage(language)
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language.startsWith('ar') ? 'ar' : 'en')
  } catch {
    // The language still changes for this session when browser storage is unavailable.
  }
})

applyDocumentLanguage(getInitialLanguage())

export default i18n
